pub struct Lang(pub &'static T);

impl Global for Lang {}

pub fn t(cx: &App) -> &'static T {
    cx.global::<Lang>().0
}

/// 存过的选择，否则看系统界面语言
pub fn initial(saved: Option<&str>) -> &'static T {
    match saved {
        Some("zh") => &ZH,
        Some(_) => &EN,
        // LANG_CHINESE = 0x04
        None if unsafe { windows::Win32::Globalization::GetUserDefaultUILanguage() } & 0x3ff == 0x04 => &ZH,
        None => &EN,
    }
}
